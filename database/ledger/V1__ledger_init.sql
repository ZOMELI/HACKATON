-- ledger-service: libro de afirmaciones. Solo se insertan filas; nunca se actualizan ni se borran.
-- El esquema `ledger` lo crea el contenedor Flyway (no se crea aquí).

CREATE TABLE ledger.person (
    person_id   VARCHAR(255) PRIMARY KEY,
    full_name   VARCHAR(255),
    email       VARCHAR(255),
    created_at  TIMESTAMP
);

CREATE TABLE ledger.claim (
    id            BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    person_id     VARCHAR(255),
    person_name   VARCHAR(255),
    person_email  VARCHAR(255),
    dimension     VARCHAR(255),
    claim_value   VARCHAR(1000),
    source        VARCHAR(255),
    valid_from    DATE,
    valid_to      DATE,
    observed_at   DATE,
    status        VARCHAR(255),
    evidence_ref  VARCHAR(255),
    author        VARCHAR(255),
    recorded_at   TIMESTAMP
);
CREATE INDEX claim_person_idx ON ledger.claim (person_id, dimension, recorded_at DESC);
