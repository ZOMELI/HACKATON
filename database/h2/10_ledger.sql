-- Esquema LEDGER (ledger-service): libro de afirmaciones. Solo se inserta; no hay UPDATE ni DELETE.
SET SCHEMA LEDGER;

-- Registro de identidad. PERSON_ID es la matrícula o el código de proveedor; un usuario de Jira
-- que no se pudo enlazar se registra con su correo como identificador.
CREATE TABLE IF NOT EXISTS PERSON (
    PERSON_ID   VARCHAR(160) NOT NULL PRIMARY KEY,
    FULL_NAME   VARCHAR(200),
    EMAIL       VARCHAR(200),
    CREATED_AT  TIMESTAMP    NOT NULL
);

-- DIMENSION: ORG_MEMBERSHIP, ROLE, MANAGEMENT, FUNDING, OPERATIONAL_ASSIGNMENT, AVAILABILITY, EVIDENCE, DECISION.
-- SOURCE:    JIRA, SIGA, PREPER, INVENTORY, PROVIDER_ACT, MOVIPER, EMAIL, CASE_DECISION.
-- STATUS:    ASSERTED, FORECAST, CONFIRMED, PENDING.
CREATE TABLE IF NOT EXISTS CLAIM (
    ID            BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    PERSON_ID     VARCHAR(160)  NOT NULL,
    PERSON_NAME   VARCHAR(200),
    PERSON_EMAIL  VARCHAR(200),
    DIMENSION     VARCHAR(40)   NOT NULL,
    CLAIM_VALUE   VARCHAR(1000) NOT NULL,
    SOURCE        VARCHAR(40)   NOT NULL,
    VALID_FROM    DATE,
    VALID_TO      DATE,
    OBSERVED_AT   DATE,
    STATUS        VARCHAR(20)   NOT NULL,
    EVIDENCE_REF  VARCHAR(300),
    AUTHOR        VARCHAR(160),
    RECORDED_AT   TIMESTAMP     NOT NULL
);

CREATE INDEX IF NOT EXISTS IDX_CLAIM_PERSON ON CLAIM (PERSON_ID, DIMENSION);
CREATE INDEX IF NOT EXISTS IDX_CLAIM_DIMENSION ON CLAIM (DIMENSION, STATUS);
