-- Esquema AGENTS (agents-service): registro de lo que produjo cada agente, para auditoría.
SET SCHEMA AGENTS;

-- EVIDENCE_TYPE: MOVEMENT_APPROVAL, SWAP_CONSENT, ACT_RENEWAL, ACT_REPLACEMENT, TEMPORARY_SUPPORT,
--                INFORMAL_NEED, IRRELEVANT.
-- GENERATED_BY:  MODEL o RECORDED (respaldo sin modelo).
CREATE TABLE IF NOT EXISTS EVIDENCE_EXTRACTION (
    ID             BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    EMAIL_ID       VARCHAR(300)  NOT NULL,
    EVIDENCE_TYPE  VARCHAR(40)   NOT NULL,
    PERSON_IDS     VARCHAR(1000),
    REFERENCE_IDS  VARCHAR(1000),
    APPROVER       VARCHAR(300),
    QUOTE          VARCHAR(2000),
    GENERATED_BY   VARCHAR(20)   NOT NULL,
    CREATED_AT     TIMESTAMP     NOT NULL
);

CREATE TABLE IF NOT EXISTS CASE_SUMMARY (
    ID            BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    CASE_ID       BIGINT        NOT NULL,
    SUMMARY       VARCHAR(4000),
    GENERATED_BY  VARCHAR(20)   NOT NULL,
    CREATED_AT    TIMESTAMP     NOT NULL
);

CREATE INDEX IF NOT EXISTS IDX_CASE_SUMMARY_CASE ON CASE_SUMMARY (CASE_ID);
