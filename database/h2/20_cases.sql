-- Esquema CASES (cases-service): casos, decisiones y configuración de alertas.
SET SCHEMA CASES;

-- CASE_TYPE: SWAP, TEMPORARY_SUPPORT, CATEGORY_MISMATCH, INVENTORY_LAG, ACT_REPLACEMENT,
--            NO_FUNDING, UNLINKED_IDENTITY, EXPIRATION.
-- STATUS:    OPEN, RESOLVED.
-- CASE_KEY:  clave de negocio; impide abrir dos veces el mismo caso.
CREATE TABLE IF NOT EXISTS CASE_FILE (
    ID         BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    CASE_TYPE  VARCHAR(40)   NOT NULL,
    TITLE      VARCHAR(300)  NOT NULL,
    STATUS     VARCHAR(20)   NOT NULL,
    OWNER_ID   VARCHAR(160),
    DUE_DATE   DATE,
    OPENED_AT  TIMESTAMP     NOT NULL,
    SUMMARY    VARCHAR(4000),
    CASE_KEY   VARCHAR(300)  NOT NULL,
    CONSTRAINT UQ_CASE_FILE_KEY UNIQUE (CASE_KEY)
);

CREATE TABLE IF NOT EXISTS CASE_PERSON (
    CASE_ID    BIGINT       NOT NULL,
    PERSON_ID  VARCHAR(160) NOT NULL,
    PRIMARY KEY (CASE_ID, PERSON_ID),
    CONSTRAINT FK_CASE_PERSON_CASE FOREIGN KEY (CASE_ID) REFERENCES CASE_FILE (ID)
);

-- Opciones de decisión que las reglas definieron para el caso, en orden.
CREATE TABLE IF NOT EXISTS CASE_OPTION (
    CASE_ID      BIGINT      NOT NULL,
    ITEM_ORDER   INT         NOT NULL,
    OPTION_CODE  VARCHAR(60) NOT NULL,
    PRIMARY KEY (CASE_ID, ITEM_ORDER),
    CONSTRAINT FK_CASE_OPTION_CASE FOREIGN KEY (CASE_ID) REFERENCES CASE_FILE (ID)
);

CREATE TABLE IF NOT EXISTS DECISION (
    ID           BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    CASE_ID      BIGINT       NOT NULL,
    OPTION_CODE  VARCHAR(60)  NOT NULL,
    DECIDED_BY   VARCHAR(160) NOT NULL,
    DECIDED_AT   TIMESTAMP    NOT NULL,
    VALID_UNTIL  DATE,
    NOTE         VARCHAR(1000),
    CONSTRAINT FK_DECISION_CASE FOREIGN KEY (CASE_ID) REFERENCES CASE_FILE (ID)
);

-- Una sola fila (ID = 1): días de anticipación de las alertas de vencimiento.
CREATE TABLE IF NOT EXISTS ALERT_SETTING (
    ID                 INT NOT NULL PRIMARY KEY,
    FIRST_ALERT_DAYS   INT NOT NULL,
    SECOND_ALERT_DAYS  INT NOT NULL
);

INSERT INTO ALERT_SETTING (ID, FIRST_ALERT_DAYS, SECOND_ALERT_DAYS)
SELECT 1, 60, 30 WHERE NOT EXISTS (SELECT 1 FROM ALERT_SETTING WHERE ID = 1);

CREATE INDEX IF NOT EXISTS IDX_CASE_FILE_STATUS ON CASE_FILE (STATUS, CASE_TYPE);
CREATE INDEX IF NOT EXISTS IDX_CASE_FILE_OWNER ON CASE_FILE (OWNER_ID);
