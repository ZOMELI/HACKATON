-- Esquema INGESTION (ingestion-service): historial de sincronizaciones, fuente por fuente.
SET SCHEMA INGESTION;

-- STATUS: RUNNING, COMPLETED, PARTIAL (alguna fuente falló).
CREATE TABLE IF NOT EXISTS SYNC_RUN (
    ID           BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    STARTED_AT   TIMESTAMP   NOT NULL,
    FINISHED_AT  TIMESTAMP,
    STATUS       VARCHAR(20) NOT NULL,
    CLAIMS_SENT  INT         NOT NULL
);

-- STATUS por fuente: OK, FAILED, NOT_IMPLEMENTED.
CREATE TABLE IF NOT EXISTS SYNC_SOURCE_RESULT (
    SYNC_RUN_ID  BIGINT      NOT NULL,
    ITEM_ORDER   INT         NOT NULL,
    SOURCE       VARCHAR(40) NOT NULL,
    STATUS       VARCHAR(20) NOT NULL,
    RECORDS      INT         NOT NULL,
    MESSAGE      VARCHAR(500),
    PRIMARY KEY (SYNC_RUN_ID, ITEM_ORDER),
    CONSTRAINT FK_SYNC_SOURCE_RESULT_RUN FOREIGN KEY (SYNC_RUN_ID) REFERENCES SYNC_RUN (ID)
);
