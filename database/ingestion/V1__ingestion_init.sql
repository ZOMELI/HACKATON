-- ingestion-service: una fila por sincronización y el resultado de cada fuente.
-- El esquema `ingestion` lo crea el contenedor Flyway (no se crea aquí).

CREATE TABLE ingestion.sync_run (
    id           BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    started_at   TIMESTAMP,
    finished_at  TIMESTAMP,
    status       VARCHAR(255),
    claims_sent  INTEGER NOT NULL
);

CREATE TABLE ingestion.sync_source_result (
    sync_run_id  BIGINT  NOT NULL REFERENCES ingestion.sync_run (id),
    item_order   INTEGER NOT NULL,
    source       VARCHAR(255),
    status       VARCHAR(255),
    records      INTEGER NOT NULL,
    message      VARCHAR(500),
    PRIMARY KEY (sync_run_id, item_order)
);
